#!/usr/bin/env python3
"""Generate the read-only parity check of the deployed objects against the hand-written SQL.

    python scripts/parity_minus.py                          # -> build/parity_minus.sql
    python scripts/run_sql.py --role CRM_TRANSFORMER build/parity_minus.sql
    make parity-check                                       # both, output in build/parity_check.txt

Why this exists
    Phase 5 replaced the objects that sql/02_data_cleaning.sql, 02b_core_models.sql and
    02c_analysis_marts.sql build with dbt-built objects of the same names. Comparing two
    snapshots (make parity-snapshot / parity-diff) needs the SQL build to be live for the
    "before" run, and `make models` would overwrite the dbt build to get it. This check needs
    neither: it rebuilds every hand-written object in the query itself and compares it with
    whatever is deployed now, without creating or replacing anything.

What it generates
    For each of the 18 objects: the body of its CREATE OR REPLACE VIEW / TABLE statement, with
    every reference to another STAGING or MART object rewritten into a CTE name (HW_<NAME>), so
    the whole chain is computed from RAW as CTEs (only the bodies the object depends on). One
    SELECT per object compares that rebuild (HW) with the deployed object of the same name:
      HW_ROWS, DEPLOYED_ROWS    COUNT(*) of each
      HW_MINUS_DEPLOYED         rows of the rebuild that the deployed object lacks, and the
      DEPLOYED_MINUS_HW         reverse (MINUS is positional: column count and order must agree)
      HASH_AGG_EQUAL            HASH_AGG(*) of both: an order-independent fingerprint of all rows
                                that also counts duplicates, which MINUS (set-based) cannot see
      PARITY                    all of the above agree
      DEPLOYED_BY               'dbt' or 'sql' from the deployed object's relation comment, so the
                                output shows which build was compared (the check passes trivially
                                when the SQL build itself is deployed)
      STATUS                    PASS when PARITY is what the row expects, else FAIL
    Two control rows prove that the comparison can fail: the deployed STG_CAMPAIGNS with one
    budget changed by 0.01 (MINUS finds it) and with one row duplicated (only COUNT and HASH_AGG
    find it). Their expected PARITY is FALSE, so they PASS only when the difference is detected.

Read-only
    USE and SELECT only; no CREATE, no temporary object. The session's current schema is RAW, so
    an unqualified name could never resolve to a STAGING or MART object, and the generator fails
    if a rewritten body still names one. run_sql.py exits 1 on any FAIL row.
Exit codes: 0 written; 2 the SQL files do not have the expected 18 CREATE statements.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sfconn  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
SQL_FILES = ["sql/02_data_cleaning.sql", "sql/02b_core_models.sql", "sql/02c_analysis_marts.sql"]
DEFAULT_OUT = REPO_ROOT / "build" / "parity_minus.sql"
EXPECTED_OBJECTS = 18

CREATE = re.compile(
    r"^CREATE\s+OR\s+REPLACE\s+(?:VIEW|TABLE)\s+MARKETING_CRM\.(STAGING|MART)\.(\w+)\s+"
    r"COMMENT\s*=\s*'(?:[^']|'')*'\s+AS\s+(.*)$",
    re.S | re.I,
)
REF = re.compile(r"\bMARKETING_CRM\.(STAGING|MART)\.(\w+)\b", re.I)

HEADER = """\
-- GENERATED by scripts/parity_minus.py from {files}.
-- Do not edit: regenerate with `make parity-check`. Read-only (USE and SELECT only).
-- One row per object: the hand-written body rebuilt from RAW as CTEs (HW) vs the deployed object.
USE ROLE CRM_TRANSFORMER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE MARKETING_WH;
USE SCHEMA MARKETING_CRM.RAW;   -- unqualified names cannot resolve to a STAGING or MART object
"""

COMPARE = """\
{ctes},
hw AS (SELECT * FROM {hw_name}),
deployed AS ({deployed_sql}),
compared AS (
  SELECT (SELECT COUNT(*) FROM hw)                                         AS HW_ROWS,
         (SELECT COUNT(*) FROM deployed)                                   AS DEPLOYED_ROWS,
         (SELECT COUNT(*) FROM (SELECT * FROM hw MINUS SELECT * FROM deployed)) AS HW_MINUS_DEPLOYED,
         (SELECT COUNT(*) FROM (SELECT * FROM deployed MINUS SELECT * FROM hw)) AS DEPLOYED_MINUS_HW,
         EQUAL_NULL((SELECT HASH_AGG(*) FROM hw), (SELECT HASH_AGG(*) FROM deployed)) AS HASH_AGG_EQUAL
)
SELECT '{label}' AS OBJECT_NAME, HW_ROWS, DEPLOYED_ROWS, HW_MINUS_DEPLOYED, DEPLOYED_MINUS_HW, HASH_AGG_EQUAL,
       (HW_ROWS = DEPLOYED_ROWS AND HW_MINUS_DEPLOYED = 0 AND DEPLOYED_MINUS_HW = 0 AND HASH_AGG_EQUAL) AS PARITY,
       {expected} AS EXPECTED_PARITY,
       (SELECT CASE WHEN CONTAINS(COMMENT, 'Built by dbt') THEN 'dbt'
                    WHEN CONTAINS(COMMENT, 'sql/02') THEN 'sql' ELSE 'unknown' END
        FROM MARKETING_CRM.INFORMATION_SCHEMA.TABLES
        WHERE TABLE_SCHEMA = '{schema}' AND TABLE_NAME = '{name}')       AS DEPLOYED_BY,
       IFF(PARITY = EXPECTED_PARITY, 'PASS', 'FAIL') AS STATUS
FROM compared"""

# Controls: the deployed STG_CAMPAIGNS, altered in a way the check must detect.
CONTROLS = [
    ("CONTROL budget +0.01 (MINUS finds it)",
     "SELECT * REPLACE (IFF(CAMPAIGN_ID = 'CMP0001', BUDGET + 0.01, BUDGET) AS BUDGET) "
     "FROM MARKETING_CRM.STAGING.STG_CAMPAIGNS"),
    ("CONTROL one row twice (only COUNT, HASH)",
     "SELECT * FROM MARKETING_CRM.STAGING.STG_CAMPAIGNS UNION ALL "
     "SELECT * FROM MARKETING_CRM.STAGING.STG_CAMPAIGNS WHERE CAMPAIGN_ID = 'CMP0001'"),
]


def extract_bodies() -> dict[str, tuple[str, str, str]]:
    """{'SCHEMA.NAME': (schema, name, body with references rewritten)}, in build order."""
    bodies: dict[str, tuple[str, str, str]] = {}
    for rel in SQL_FILES:
        for statement in sfconn.split_sql((REPO_ROOT / rel).read_text(encoding="utf-8")):
            match = CREATE.match(statement)
            if not match:
                continue
            schema, name = match.group(1).upper(), match.group(2).upper()
            body = match.group(3).rstrip().rstrip(";").rstrip()
            body = REF.sub(lambda r: f"HW_{r.group(2).upper()}", body)
            leftover = re.search(r"MARKETING_CRM\.(STAGING|MART)\b", body, re.I)
            if leftover:
                raise SystemExit(f"FAIL  {rel}: {schema}.{name} still names {leftover.group(0)} after rewriting")
            bodies[f"{schema}.{name}"] = (schema, name, body)
    return bodies


def dependencies(key: str, bodies: dict[str, tuple[str, str, str]]) -> list[str]:
    """The objects whose bodies `key` needs (itself included), in build order."""
    by_cte = {f"HW_{name}": k for k, (_s, name, _b) in bodies.items()}
    needed, stack = set(), [key]
    while stack:
        current = stack.pop()
        if current in needed:
            continue
        needed.add(current)
        for cte in re.findall(r"\bHW_\w+\b", bodies[current][2]):
            stack.append(by_cte[cte])
    return [k for k in bodies if k in needed]


def build_sql(bodies: dict[str, tuple[str, str, str]], only: list[str]) -> str:
    def ctes_for(key: str) -> str:
        return "WITH " + ",\n".join(f"HW_{bodies[k][1]} AS (\n{bodies[k][2]}\n)" for k in dependencies(key, bodies))

    statements = []
    for key in only:
        schema, name, _ = bodies[key]
        statements.append(COMPARE.format(
            ctes=ctes_for(key), hw_name=f"HW_{name}", label=key, expected="TRUE", schema=schema, name=name,
            deployed_sql=f"SELECT * FROM MARKETING_CRM.{schema}.{name}"))
    for label, deployed_sql in CONTROLS:
        statements.append(COMPARE.format(
            ctes=ctes_for("STAGING.STG_CAMPAIGNS"), hw_name="HW_STG_CAMPAIGNS", label=label, expected="FALSE",
            schema="STAGING", name="STG_CAMPAIGNS", deployed_sql=deployed_sql))
    return HEADER.format(files=", ".join(SQL_FILES)) + "\n" + ";\n\n".join(statements) + ";\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("objects", nargs="*", help="SCHEMA.NAME to check (default: all 18)")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="where to write the SQL")
    args = parser.parse_args(argv)
    bodies = extract_bodies()
    if len(bodies) != EXPECTED_OBJECTS:
        print(f"FAIL  expected {EXPECTED_OBJECTS} CREATE statements in {', '.join(SQL_FILES)}, found {len(bodies)}")
        return 2
    only = [o.upper() for o in args.objects] or list(bodies)
    unknown = [o for o in only if o not in bodies]
    if unknown:
        print(f"FAIL  unknown object(s): {', '.join(unknown)}; known: {', '.join(bodies)}")
        return 2
    out = args.out if args.out.is_absolute() else Path.cwd() / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_sql(bodies, only), encoding="utf-8")
    print(f"wrote {out.relative_to(REPO_ROOT) if out.is_relative_to(REPO_ROOT) else out}: "
          f"{len(only)} object(s) + {len(CONTROLS)} control rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
